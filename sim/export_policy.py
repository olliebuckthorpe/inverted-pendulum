"""Export a trained SAC actor for the Pico (PLAN 6.1).

Writes, for checkpoints/<tag>.zip:
  ../firmware/nn/weights/<tag>.bin  16-byte header ("PPOL", version 1, n_in, n_floats as uint32 LE… see below)
                                    + 4673 float32 little-endian, in mlp_policy.h's Weights order
  ../firmware/nn/weights/<tag>.h    the same numbers as a compiled-in C++ constant (POLICY_WEIGHTS)
Usage: uv run python export_policy.py balanceG_seed0
"""
import struct
import sys

import numpy as np
from stable_baselines3 import SAC

import model

OUT = model.SIM_DIR.parent / "firmware" / "nn" / "weights"
MAGIC, VERSION = b"PPOL", 1


def flat_weights(tag: str) -> np.ndarray:
    actor = SAC.load(model.SIM_DIR / "checkpoints" / f"{tag}.zip", device="cpu").policy.actor
    l1, l2 = [m for m in actor.latent_pi if hasattr(m, "weight")]
    parts = [l1.weight, l1.bias, l2.weight, l2.bias, actor.mu.weight.reshape(-1), actor.mu.bias]
    return np.concatenate([t.detach().numpy().astype(np.float32).ravel() for t in parts])   # row-major = w[out][in]


def export(tag: str) -> np.ndarray:
    f = flat_weights(tag)
    assert f.size == 6 * 64 + 64 + 64 * 64 + 64 + 64 + 1 == 4673, f.size   # = policy::N_FLOATS
    OUT.mkdir(parents=True, exist_ok=True)
    header = MAGIC + struct.pack("<HHII", VERSION, 6, f.size, 0)   # last field reserved (CRC once the protocol has one)
    (OUT / f"{tag}.bin").write_bytes(header + f.astype("<f4").tobytes())
    body = ",\n".join(", ".join(f"{v:.9g}f" for v in f[i:i + 8]) for i in range(0, f.size, 8))
    (OUT / f"{tag}.h").write_text(
        f"// Generated by sim/export_policy.py from checkpoints/{tag}.zip — do not edit.\n#pragma once\n"
        f'#include "../mlp_policy.h"\n'
        f"// Flat list in Weights order: C++ brace elision fills w1, b1, w2, b2, w3, b3 in turn.\n"
        f"static const policy::Weights POLICY_WEIGHTS = {{\n{body}\n}};\n")
    return f


if __name__ == "__main__":
    for tag in sys.argv[1:]:
        export(tag)
        print(f"exported {tag}: {OUT / (tag + '.bin')} and .h")
